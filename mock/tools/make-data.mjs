// Writes src/data.js from the case's test-environment/test-customers.json (no dependencies):
//
//   node tools/make-data.mjs <case>/test-environment/test-customers.json
//
// The file becomes a plain `export default {...}` module, so wrangler bundles it as is and node
// imports it without JSON import attributes. Values go through JSON.parse/JSON.stringify: field
// order, strings, nulls and numbers are kept; the only visible change is number spelling
// (0.0 -> 0, 12000.0 -> 12000), which is the same JSON value.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node tools/make-data.mjs <case>/test-environment/test-customers.json');
  process.exit(2);
}
const data = JSON.parse(fs.readFileSync(src, 'utf8'));
if (!Array.isArray(data.customers)) throw new Error('no customers[] in ' + src);
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/data.js');
const lines = data.customers.map((c) => '    ' + JSON.stringify(c));
const text = `// GENERATED by tools/make-data.mjs from test-environment/test-customers.json. Do not edit by hand:
// change the case file and run the tool again. One customer per line.
export default {
  description: ${JSON.stringify(data.description ?? '')},
  customers: [
${lines.join(',\n')},
  ],
};
`;
fs.writeFileSync(out, text);
console.log(`wrote ${out}: ${data.customers.length} customers, ${text.length} bytes`);
